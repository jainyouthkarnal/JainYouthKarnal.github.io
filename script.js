// Bhajan search + tag filtering. Edit each card's data-tags to add future tags.
(function initBhajanSearch(){
  const input=document.getElementById('bhajan-search');
  const cards=[...document.querySelectorAll('.bhajan-card')];
  const tagWrap=document.getElementById('bhajan-tags');
  const empty=document.getElementById('bhajan-empty');
  if(!input||!cards.length||!tagWrap)return;
  const tags=[...new Set(cards.flatMap(card=>(card.dataset.tags||'').split(',').map(t=>t.trim().toLowerCase()).filter(Boolean)))].sort();
  let activeTag='all';
  const makeTag=(label,tag)=>{const b=document.createElement('button');b.type='button';b.className='bhajan-filter'+(tag==='all'?' active':'');b.textContent=label;b.dataset.tag=tag;b.addEventListener('click',()=>{activeTag=tag;tagWrap.querySelectorAll('.bhajan-filter').forEach(x=>x.classList.toggle('active',x===b));apply();});return b;};
  tagWrap.appendChild(makeTag('All','all'));
  tags.forEach(tag=>tagWrap.appendChild(makeTag(tag,tag)));
  const apply=()=>{const q=input.value.trim().toLowerCase();let visible=0;cards.forEach(card=>{const hay=`${card.dataset.title||''} ${card.dataset.tags||''} ${card.textContent}`.toLowerCase();const okTag=activeTag==='all'||(card.dataset.tags||'').toLowerCase().split(',').includes(activeTag);const okSearch=!q||hay.includes(q);const show=okTag&&okSearch;card.hidden=!show;if(show)visible++;});if(empty)empty.hidden=visible!==0;};
  input.addEventListener('input',apply);
  apply();
})();

