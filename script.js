window.initTripMedia=async function initTripMedia(){

  const boxes=[
    ...document.querySelectorAll(
      '.trip-media-links'
    )
  ];

  if(!boxes.length)return;

  let man={};

  try{

    const r=
      await fetch(
        'data/trip-media.json'
      );

    if(r.ok)
      man=await r.json();

  }catch(e){}

  boxes.forEach(box=>{

    const folder=
      box.dataset.folder;

    const info=
      man[folder]||{};

    const place=
      (
        box
          .closest('.trip-card')
          ?.querySelector('h3')||
        {}
      ).textContent||'';

    let any=false;

    box
      .querySelectorAll('a')
      .forEach(a=>{

        const href=
          a.getAttribute('href')||'';

        const cat=
          (
            href.match(
              /\/([a-z]+)\/?$/
            )||[]
          )[1];

        const files=
          (info[cat]||[])
            .filter(Boolean);

        if(!files.length){

          a.hidden=true;

          return;

        }

        any=true;

        a.dataset.count=
          files.length;

        a.setAttribute(
          'href',
          '#'
        );

        a.addEventListener(
          'click',
          e=>{

            e.preventDefault();

            JYKLB.open(
              files.map(
                f=>
                  `assets/trips/${folder}/${cat}/${f}`
              ),
              0,
              files.map(
                ()=>`${place} — ${a.textContent}`
              )
            );

          }
        );

      });

    box.hidden=!any;

  });

};

