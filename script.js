(function initDropdowns(){

  const items=[
    ...document.querySelectorAll(
      '.nav-item.has-sub'
    )
  ];

  if(!items.length)return;

  const closeAll=except=>
    items.forEach(i=>{

      if(i===except)return;

      i.classList.remove('open');

      const b=
        i.querySelector(
          '.nav-trigger'
        );

      if(b)
        b.setAttribute(
          'aria-expanded',
          'false'
        );

    });

  items.forEach(i=>{

    const b=
      i.querySelector(
        '.nav-trigger'
      );

    if(!b)return;

    b.addEventListener(
      'click',
      e=>{

        e.stopPropagation();

        const o=
          !i.classList.contains(
            'open'
          );

        closeAll(i);

        i.classList.toggle(
          'open',
          o
        );

        b.setAttribute(
          'aria-expanded',
          String(o)
        );

      }
    );

  });

  document.addEventListener(
    'click',
    e=>{
      if(
        !e.target.closest(
          '.nav-item'
        )
      ){
        closeAll();
      }
    }
  );

  document.addEventListener(
    'keydown',
    e=>{
      if(e.key==='Escape')
        closeAll();
    }
  );

})();


