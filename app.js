(function initScrollProgress(){

  const bar=document.querySelector('.scroll-progress');

  if(!bar)return;

  const update=()=>{
    const h=
      document.documentElement.scrollHeight-
      window.innerHeight;

    const p=h>0?
      window.scrollY/h:
      0;

    bar.style.transform=
      `scaleX(${Math.min(1,p)})`;
  };

  addEventListener('scroll',update,{passive:true});
  addEventListener('resize',update);
  update();

})();


