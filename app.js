const JYKLB=(function(){

  let lb,big,list=[],alts=[],i=0;

  function show(n){

    i=(n+list.length)%list.length;

    big.src=list[i];

    big.alt=alts[i]||'';

    big.style.animation='none';

    big.offsetWidth;

    big.style.animation='';

    lb.classList.toggle(
      'single',
      list.length<2
    );
  }

  function close(){

    lb.classList.remove('open');

    document.body.style.overflow='';
  }

  function build(){

    if(lb)return;

    lb=document.createElement('div');

    lb.className='lightbox';

    lb.setAttribute(
      'role',
      'dialog'
    );

    lb.setAttribute(
      'aria-modal',
      'true'
    );

    lb.setAttribute(
      'aria-label',
      'Image viewer'
    );

    lb.innerHTML=
      '<button class="lb-close" type="button" aria-label="Close">×</button>'+
      '<button class="lb-prev" type="button" aria-label="Previous">‹</button>'+
      '<img alt="">'+
      '<button class="lb-next" type="button" aria-label="Next">›</button>';

    document.body.appendChild(lb);

    big=lb.querySelector('img');

    lb.addEventListener('click',e=>{

      if(
        e.target===lb||
        e.target.closest('.lb-close')
      ){
        close();
      }

      else if(
        e.target.closest('.lb-prev')
      ){
        show(i-1);
      }

      else if(
        e.target.closest('.lb-next')
      ){
        show(i+1);
      }

    });

    addEventListener(
      'keydown',
      e=>{

        if(!lb.classList.contains('open'))
          return;

        if(e.key==='Escape')
          close();

        if(e.key==='ArrowLeft')
          show(i-1);

        if(e.key==='ArrowRight')
          show(i+1);

      }
    );
  }

  return{
    open(srcs,n,al){

      build();

      list=srcs;

      alts=al||[];

      show(n||0);

      lb.classList.add('open');

      document.body.style.overflow='hidden';
    }
  };

})();


