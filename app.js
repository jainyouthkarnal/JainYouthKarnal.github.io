function renderCalendar(){

  if(!calGrid||!calMonth)
    return;

  const y=calDate.getFullYear();
  const m=calDate.getMonth();

  const first=
    new Date(y,m,1);

  const days=
    new Date(y,m+1,0)
      .getDate();

  const start=
    first.getDay();

  calMonth.textContent=
    first.toLocaleDateString(
      document.documentElement.lang==='hi'
        ?'hi-IN'
        :'en-IN',
      {
        month:'long',
        year:'numeric'
      }
    );

  calGrid.innerHTML='';

  for(
    let i=0;
    i<start;
    i++
  ){

    const e=
      document.createElement('div');

    e.className=
      'cal-day empty';

    calGrid.appendChild(e);

  }

  for(
    let d=1;
    d<=days;
    d++
  ){

    const e=
      document.createElement('div');

    e.className='cal-day';

    const dateKey=
      `${y}-${pad(m+1)}-${pad(d)}`;

    const dow=
      new Date(
        y,
        m,
        d
      ).getDay();

    const n=
      document.createElement('strong');

    n.textContent=d;

    e.appendChild(n);

    const trip=
      tripEvents[dateKey];

    if(trip){

      e.classList.add(
        'has-event',
        'trip-day'
      );

      const lab=
        document.createElement('span');

      lab.textContent=
        trip.title;
      if(trip.note) lab.title=trip.note;
      e.appendChild(lab);

    }

    const kal=
      kalyanakEvents[dateKey];

    if(kal){

      e.classList.add(
        'has-event',
        'kalyanak-day'
      );

      if(
        kal.some(k=>k.star)
      ){
        e.classList.add(
          'mahavir-day'
        );
      }

      kal.forEach(k=>{

        const lab=
          document.createElement('span');

        lab.className=
          'kal'+
          (k.star?' star':'');

        const txt=
          document.documentElement.lang==='hi'
            ?k.hi
            :k.en;

        lab.textContent=txt;

        lab.title=
          `${k.en} | ${k.hi}`;

        e.appendChild(lab);

      });

    }

    if(
      dow===0&&
      !trip
    ){

      e.classList.add(
        'path-day'
      );

      const lab=
        document.createElement('span');

      lab.textContent=
        document.documentElement.lang==='hi'
          ?'पाठशाला'
          :'Pathshala';

      e.appendChild(lab);

    }

    calGrid.appendChild(e);

  }

}

